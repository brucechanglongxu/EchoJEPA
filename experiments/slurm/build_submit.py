"""Emit a Bash script that submits all SonoState training cells to Slurm and
chains each cell's analyses via --dependency=afterok:<train_jobid>.

Reads experiments/configs/_generated/manifest.json (created by
generate_sweeps.py) and writes a single submitter script.

Usage:
    python experiments/slurm/build_submit.py \
        --manifest experiments/configs/_generated/manifest.json \
        --out      experiments/slurm/_submit.sh \
        --data-root /mnt/vast/data/brucexu/echonet
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

ANALYSES: list[tuple[str, str]] = [
    # (script_name, common-extra-args  -- $DATA_ROOT will be substituted)
    ("forecast_curves",
     "--csv $DATA_ROOT/FileList.csv --video-root $DATA_ROOT/EchoNet-Dynamic/Videos"),
    ("phase_decoding",
     "--filelist-csv $DATA_ROOT/FileList.csv --vt-csv $DATA_ROOT/VolumeTracings.csv "
     "--video-root $DATA_ROOT/EchoNet-Dynamic/Videos"),
    ("heart_rate",
     "--filelist-csv $DATA_ROOT/FileList.csv --vt-csv $DATA_ROOT/VolumeTracings.csv "
     "--video-root $DATA_ROOT/EchoNet-Dynamic/Videos"),
    ("geometry",
     "--csv $DATA_ROOT/FileList.csv --video-root $DATA_ROOT/EchoNet-Dynamic/Videos"),
    ("ef_probe",
     "--csv $DATA_ROOT/FileList.csv --video-root $DATA_ROOT/EchoNet-Dynamic/Videos --target EF"),
    ("cycle_consistency",
     "--csv $DATA_ROOT/FileList.csv --video-root $DATA_ROOT/EchoNet-Dynamic/Videos"),
]


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--manifest", required=True)
    p.add_argument("--out", required=True,
                   help="Path of the bash submitter script to emit.")
    p.add_argument("--data-root", default="/mnt/vast/data/brucexu/echonet")
    p.add_argument("--repo",
                   default=str(Path(__file__).resolve().parents[2]),
                   help="EchoJEPA repo root (passed as REPO env to sbatch).")
    p.add_argument("--account", default="mai-ws-ai-infra")
    p.add_argument("--partition", default="hpc-mid")
    p.add_argument("--analysis-partition", default=None,
                   help="If set, override --partition for analysis jobs only.")
    args = p.parse_args()

    with open(args.manifest) as f:
        cells = json.load(f)

    train_sbatch = "experiments/slurm/train_cell.sbatch"
    ana_sbatch   = "experiments/slurm/analyse_cell.sbatch"

    lines: list[str] = []
    lines.append("#!/usr/bin/env bash")
    lines.append("# Auto-generated by experiments/slurm/build_submit.py -- DO NOT EDIT BY HAND.")
    lines.append("set -euo pipefail")
    lines.append(f'cd "{args.repo}"')
    lines.append('mkdir -p /mnt/vast/exp/brucexu/EchoJEPA/logs')
    lines.append("")
    lines.append('JOBIDS_FILE=${JOBIDS_FILE:-experiments/slurm/_submitted_jobs.txt}')
    lines.append(': > "$JOBIDS_FILE"')
    lines.append("")
    lines.append('echo "Submitting %d training cells + %d analyses each = %d total jobs"' %
                 (len(cells), len(ANALYSES), len(cells) * (1 + len(ANALYSES))))
    lines.append("")

    ana_part = args.analysis_partition or args.partition
    for cell in cells:
        tag = f"{cell['sweep']}__{cell['cell']}"
        cfg = cell["config"]
        folder = cell["folder"]
        ck = f"{folder}/latest.pt"

        lines.append(f"# ==== {tag} ====")
        lines.append(
            f'TRAIN_ID=$(sbatch --parsable '
            f'-A {args.account} -p {args.partition} '
            f'-J sono-tr-{tag} '
            f'--export=ALL,REPO="{args.repo}",CONFIG="{cfg}" '
            f'{train_sbatch})'
        )
        lines.append(f'echo "train  {tag}  jobid=$TRAIN_ID" | tee -a "$JOBIDS_FILE"')

        for script, extra in ANALYSES:
            full_extra = extra.replace("$DATA_ROOT", args.data_root)
            ana_out = f"{folder}/analysis_{script}"
            # Quote the extra for shell-safety (single string).
            extra_q = full_extra.replace('"', '\\"')
            lines.append(
                f'ANA_ID=$(sbatch --parsable '
                f'-A {args.account} -p {ana_part} '
                f'-J sono-an-{script}-{tag} '
                f'--dependency=afterok:$TRAIN_ID '
                f'--export=ALL,REPO="{args.repo}",SCRIPT="{script}",'
                f'CHECKPOINT="{ck}",OUT="{ana_out}",EXTRA="{extra_q}" '
                f'{ana_sbatch})'
            )
            lines.append(f'echo "ana    {script:18s} {tag}  jobid=$ANA_ID  parent=$TRAIN_ID" | tee -a "$JOBIDS_FILE"')
        lines.append("")

    lines.append('echo "Done. Job ids in $JOBIDS_FILE"')
    lines.append('echo "Watch:  squeue -u $USER  /  sacct -j $(awk \'{print $NF}\' \"$JOBIDS_FILE\" | tr \"\\n\" \",\")"')

    out = Path(args.out)
    out.write_text("\n".join(lines) + "\n")
    out.chmod(0o755)
    print(f"wrote submitter -> {out}  ({len(cells)} train + {len(cells)*len(ANALYSES)} ana jobs)")


if __name__ == "__main__":
    main()
